"""Sound events and the audio frame table (ruling R3) + the expected lengths of the slice manifest.

* `game/data/audio/clip_events.json` (frozen) — per clip `{len_f, events: [{f, type, id, vol_db?}]}`: the frames the
  sound was placed on in 2D. A clip spec with `audio="table"` (the default) gets every sound event of its row copied
  into the sidecar (any sound event the spec placed itself is an error) and the bake FAILS when the row has a
  `len_f` that differs from the clip's length. `audio="own"` (loops / locomotion retimed to the 3D gaits): the spec
  places its own contact sounds (ids from `game/audio/sfx_map.json`) and `rows_md()` lists them for `r3d-integrate`
  (`docs/review/r3d-anim/audio_rows.md`), which regenerates the table from the 3D sidecars.
* The manifest (`docs/review/s2-view/slice_clips.md`, the Stage-2 `SliceClips.build()` table): `expect` frames per clip
  (-1 = any, loops allowed where `loop` is "yes"). `SliceClips.build3d` replaces it once `r3d-view3d` lands it (the lint
  reads that at runtime; the bake only warns from the markdown).
"""
import json, os, re

from .paths import repo_root


class AudioError(Exception):
    pass


_T = {}


def _load(rel):
    p = os.path.join(repo_root(), rel)
    if p not in _T:
        _T[p] = json.load(open(p)) if os.path.exists(p) else {}
    return _T[p]


def audio_table():
    return (_load("game/data/audio/clip_events.json").get("clips") or {})


def sound_ids():
    m = _load("game/audio/sfx_map.json")
    ids = set()
    for k in ("files", "banks", "aliases", "cycles", "sequences"):
        v = m.get(k) or {}
        ids.update(v.keys() if isinstance(v, dict) else [])
    return ids


def manifest():
    """{clip: {expect, tol, loop}} parsed from the Stage-2 manifest markdown."""
    p = os.path.join(repo_root(), "docs/review/s2-view/slice_clips.md")
    out = {}
    if not os.path.exists(p):
        return out
    for line in open(p):
        m = re.match(r"\|\s*`([^`]+)`\s*\|\s*(\w+)\s*\|\s*(-?\d+)\s*\|\s*(\d+)\s*\|\s*(yes)?\s*\|", line)
        if m:
            out[m.group(1)] = {"expect": int(m.group(3)), "tol": int(m.group(4)), "loop": m.group(5) == "yes"}
    return out


def apply(clip):
    """Merge the audio table into `clip.events` (audio="table"); returns a list of warnings."""
    warn = []
    ids = sound_ids()
    own = [e for e in clip.events if e["type"] in ("sfx", "voice")]
    for e in own:
        if e.get("id") not in ids:
            raise AudioError("%s: sound id '%s' at f%d is not in sfx_map.json" % (clip.id, e.get("id"), e["f"]))
    row = audio_table().get(clip.id)
    if clip.audio == "own" or row is None:
        if clip.audio == "table" and own and row is None:
            warn.append("%s has no audio-table row: its %d sound event(s) are new rows for r3d-integrate" % (clip.id, len(own)))
        return warn
    if own:
        raise AudioError("%s: audio='table' copies the audio table's sounds — remove the %d sound event(s) placed "
                         "in the spec, or set audio='own' (a retimed loop) and list the new frames" % (clip.id, len(own)))
    lf = row.get("len_f")
    if lf is not None and int(lf) != clip.length:
        raise AudioError("%s: length %d f but the audio table (clip_events.json) times its sounds on a %d f clip — "
                         "keep the 2D length (R3)" % (clip.id, clip.length, int(lf)))
    for e in row.get("events", []):
        if int(e["f"]) > clip.length:
            raise AudioError("%s: audio-table sound '%s' at f%d is past the clip's end (%d)" % (clip.id, e.get("id"), e["f"], clip.length))
        ev = {k: v for k, v in e.items()}
        clip.events.append(ev)
    return warn


def expected(clip_id):
    return manifest().get(clip_id)


def rows_md(sidecars):
    """Markdown table of every sound event of `audio="own"` clips (sidecar dicts with source.audio == "own")."""
    lines = ["# Audio rows from the 3D sidecars (for `r3d-integrate`: regenerate `game/data/audio/clip_events.json`)", "",
             "Clips retimed to the 3D gaits place their own contact sounds (ruling R3). One row per clip: its length and",
             "every sound event (frame, id, volume). Generated by `tools/art3d/anim/bake.sh`; do not edit by hand.", "",
             "| clip | len_f | loop | sound events (f id [dB]) |", "|---|---|---|---|"]
    for sc in sorted(sidecars, key=lambda s: s["clip"]):
        evs = [e for e in sc.get("events", []) if e.get("type") in ("sfx", "voice")]
        txt = ", ".join("%d %s%s" % (e["f"], e["id"], (" %+.1f" % e["vol_db"]) if "vol_db" in e else "") for e in evs) or "—"
        lines.append("| `%s` | %s | %s | %s |" % (sc["clip"], "null" if sc.get("loop") else sc["length"], "yes" if sc.get("loop") else "",
                                                   txt))
    return "\n".join(lines) + "\n"
