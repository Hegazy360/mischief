@sfx("sad_violin", max_dur=1.4, level=-19.0, desc="a lone violin weeps two falling notes under the quivering lip")
def sad_violin(rng):
    d1, d2 = 0.42, 0.62
    n = ns(d1 + d2 + 0.2)
    f = np.full(n, midi(69))
    k = ns(d1)
    g = np.arange(n - k) / SR
    f[k:] = midi(65) + (midi(69) - midi(65)) * np.exp(-g / 0.03)
    y = I.bowed(f, d1 + d2, 0.8, rng, vib=0.018, attack=0.09, release=0.2, section=1, bright=0.55)
    return y[:n]


@sfx("sniffle", cat="soft", max_dur=0.5, level=-20.0, desc="he sniffs the tear back: a wet little sniffle")
def sniffle(rng):
    def s(d, f):
        m = ns(d)
        x = filt(white(m, rng), ("bp", f, 1.3)) * env_lin([(0, 0), (0.01, 1), (d * 0.5, 0.8), (d, 0)], m)
        wet = sine(env_exp([(0, 300), (d, 520)], m), m) * env_lin([(0, 0), (0.01, 0.3), (d, 0)], m)
        return norm(x) + wet * 0.3
    return place([(0, s(0.09, 2100), 0.7), (0.14, s(0.16, 2500), 1.0)], 0.36)


