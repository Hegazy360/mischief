@sfx("kettle_pour", cat="soft", max_dur=1.3, level=-18.5,
     desc="pouring the kettle: water into the cup, the pitch rising as it fills")
def kettle_pour(rng):
    dur = 1.05
    n = ns(dur)
    x = np.linspace(0, 1, n)
    center = 520.0 * (1650.0 / 520.0) ** x * (1 + 0.12 * smooth_noise(n, 9, rng))
    stream = noise_sweep(n, rng, center, 0.9, color=-0.5)
    glug = 0.75 + 0.25 * np.sin(TAU * phase_of(11.0 + 4.0 * x, n))
    bub = place([(rng.uniform(0.05, 0.95), droplet(rng, rng.uniform(700, 2100) * (1 + 0.6 * (k / 18.0)), 0.04),
                  rng.uniform(0.2, 0.5)) for k in range(18)], dur)
    e = env_lin([(0, 0), (0.04, 1.0), (0.9, 0.9), (dur, 0)], n)
    return (norm(stream) * glug + pad(bub, n) * 0.5) * e


def _china(rng, f0: float, dur: float = 0.24, vel: float = 1.0) -> np.ndarray:
    """A spoon on a china cup: a bright inharmonic ring and a tick."""
    n = ns(dur)
    t = tt(n)
    y = np.zeros(n)
    for r, a, d in ((1.0, 1.0, 0.16), (1.47, 0.55, 0.11), (2.09, 0.35, 0.07), (2.78, 0.2, 0.05)):
        y += a * np.sin(TAU * f0 * r * t + rng.uniform(0, TAU)) * np.exp(-6.9 * t / d)
    y += burst(n, rng, 3000, 10000, 0.0001, 0.002) * 0.5
    return y * vel


