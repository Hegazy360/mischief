@sfx("tea_stir", cat="soft", max_dur=1.0, level=-21.0, desc="stirring the tea: ting-ting-ting round the cup + a swirl")
def tea_stir(rng):
    dur = 0.82
    n = ns(dur)
    tings = place([(0.02 + k * 0.13 + rng.uniform(-0.01, 0.01), _china(rng, (2900, 3150, 2750, 3050, 2950)[k], 0.18,
                                                                         (0.9, 0.7, 0.85, 0.65, 0.5)[k]))
                   for k in range(5)], dur)
    swirl = noise_sweep(n, rng, 900 * (1 + 0.3 * np.sin(TAU * 7.6 * tt(n))), 1.0) * \
        env_lin([(0, 0), (0.05, 1), (0.7, 0.8), (dur, 0)], n)
    return pad(tings, n) + norm(swirl) * 0.18


@sfx("tea_sniff", cat="soft", max_dur=0.8, level=-18.5, desc="a long, appreciative sniff of the tea (sniff-SNIIIFF)")
def tea_sniff(rng):
    def sniff(d, bright):
        m = ns(d)
        x = filt(white(m, rng), ("bp", 1900 * bright, 1.1), ("peak", 3600 * bright, 2.0, 5.0))
        return norm(x) * env_lin([(0, 0), (0.015, 0.8), (d * 0.6, 1.0), (d, 0)], m)
    return place([(0, sniff(0.1, 0.9), 0.6), (0.15, sniff(0.38, 1.12), 1.0)], 0.6)


@sfx("tea_slurp", cat="soft", max_dur=0.7, level=-17.5, desc="the posh slurp at the lip: sluuurp")
def tea_slurp(rng):
    dur = 0.46
    n = ns(dur)
    t = tt(n)
    air = filt(white(n, rng), ("bp", 1500, 0.9)) * (0.6 + 0.4 * np.sin(TAU * phase_of(34 + 12 * t / dur, n)) ** 2)
    whistle = sine(env_exp([(0, 700), (0.2, 1150), (dur, 1400)], n), n) * 0.18
    bub = place([(rng.uniform(0.02, 0.35), droplet(rng, rng.uniform(500, 1300), 0.035), rng.uniform(0.3, 0.7))
                 for _ in range(9)], dur)
    e = env_lin([(0, 0), (0.03, 1.0), (0.32, 0.9), (dur, 0)], n)
    return (norm(air) + whistle + pad(bub, n) * 0.5) * e


