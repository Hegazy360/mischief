"""Stage-2 slice kit: the sounds that live *inside clips* (ruling L12) for the Gate-0 set.

Every id here is placed by an animator as a clip event at the frame published in
docs/review/s2-sound/clip_events.md (generated by tools/audio/clip_events.py), so each
file starts on its contact sample (finalize() trims the lead-in) and is cut to the beat it
has to fit:

  ACHOO-RIA! foley   stool_scrape, slide_up_flight, sink_crash, ladle_spin (the crash →
                     300 ms of silence → one ladle spinning to rest → drips rule)
  the tea loop       stool_creak, kettle_pour, spoon_clink (2), tea_stir, tea_sniff,
                     tea_slurp, teacup_clink
  the warm-up        vase_nudge (2): the vase scoots along the mantel on each note
  micro-gags         glint, baton_swish (2), teacups_rattle, kiss_smack,
                     pinkie_wobble (voices: vo_bellows_trill /
                     _smug / _bliss in voices.py)
  last beats         bassoon_burn (slow burn: one low note, then dry silence), cravat_tug,
                     cravat_ping, bow_creak, slide_down_short, tear_plink, sad_violin, sniffle
  Bellows' feet      slipper_scuff (2): the blind shuffle
  Hush (the pit)     tinker (3), tinker_frantic, hush_phew
  event-level        door_slam (the door alone; his bonk is st_bonk's clip event),
                     ui_queued (cmd_queued), ui_nuh_uh (cmd_rejected)
"""
